from torch.utils.data import Dataset, DataLoader
from tqdm.auto import tqdm

# 1. Hardware-safe mixed precision dtype (guards against Colab T4 Turing bfloat16 crashes)
amp_dtype = (
    torch.bfloat16
    if (device == "cuda" and torch.cuda.is_bf16_supported())
    else torch.float16 if device == "cuda" else torch.float32
)
print(f"Hardware-safe AMP dtype: {amp_dtype}")

# 2. Prefetching Dataset (Decouples Disk Read + CPU Decode from GPU)
class EggImageDataset(Dataset):
    def __init__(self, paths):
        self.paths = paths

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, idx):
        path = self.paths[idx]
        image = Image.open(path).convert("RGB")
        return path, np.asarray(image)

def select_masks_vectorized(masks, scores, min_area=0.002, max_area=0.98, iou_threshold=0.70):
    """Vectorized Mask NMS — replaces O(N^2) pixel-level loops with matrix operations."""
    if len(masks) == 0:
        return []

    N, H, W = masks.shape
    flat = masks.reshape(N, -1).astype(np.float32)
    pixel_areas = flat.sum(axis=1)
    norm_areas = pixel_areas / (H * W)

    valid_idx = np.where((norm_areas >= min_area) & (norm_areas <= max_area))[0]
    if len(valid_idx) == 0:
        return []

    # Sort valid indices by descending score
    order = valid_idx[np.argsort(scores[valid_idx])[::-1]]
    flat_ordered = flat[order]
    areas_ordered = pixel_areas[order]

    # Simultaneous pairwise intersections via matrix multiplication
    intersections = flat_ordered @ flat_ordered.T
    unions = areas_ordered[:, None] + areas_ordered[None, :] - intersections
    iou_matrix = np.divide(
        intersections, unions, out=np.zeros_like(intersections), where=unions > 0
    )

    kept = []
    suppressed = np.zeros(len(order), dtype=bool)
    for i in range(len(order)):
        if suppressed[i]:
            continue
        kept.append(int(order[i]))
        # Suppress lower-scored masks with IoU > threshold
        suppressed[i + 1 :] |= iou_matrix[i, i + 1 :] > iou_threshold

    return kept

def make_overlay(image, masks, scores, kept):
    """Colour the egg masks over the original image and annotate confidence scores."""
    result = np.asarray(image).copy()

    colours = [
        (255, 60, 60),
        (40, 220, 100),
        (40, 140, 255),
        (255, 190, 30),
        (210, 70, 255),
    ]

    for instance_id, i in enumerate(kept):
        mask = masks[i]
        colour = np.array(colours[instance_id % len(colours)], dtype=np.uint8)

        result[mask] = (
            0.55 * result[mask] + 0.45 * colour
        ).astype(np.uint8)

        # Mark mask boundary without requiring OpenCV
        eroded = np.zeros_like(mask)
        eroded[1:-1, 1:-1] = (
            mask[1:-1, 1:-1]
            & mask[:-2, 1:-1]
            & mask[2:, 1:-1]
            & mask[1:-1, :-2]
            & mask[1:-1, 2:]
        )
        result[mask & ~eroded] = colour

    overlay_pil = Image.fromarray(result)

    # Annotate confidence scores directly on overlay for visual QA
    if scores is not None and len(scores) > 0 and len(kept) > 0:
        draw = ImageDraw.Draw(overlay_pil)
        for instance_id, i in enumerate(kept):
            mask = masks[i]
            y_indices, x_indices = np.where(mask)
            if len(x_indices) > 0 and len(y_indices) > 0:
                min_x, min_y = int(np.min(x_indices)), int(np.min(y_indices))
                score_val = float(scores[i])
                draw.text((min_x + 2, max(0, min_y - 12)), f"{score_val:.2f}", fill=(255, 255, 255))

    return overlay_pil

def save_outputs_worker(labels, union, overlay_img, mask_path, union_path, overlay_path):
    """Background worker function for non-blocking disk I/O."""
    for p in (mask_path, union_path, overlay_path):
        p.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(labels).save(mask_path)
    Image.fromarray(union).save(union_path)
    overlay_img.save(overlay_path, quality=90)

