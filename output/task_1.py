"""# Process every image and save the results (Asynchronous Pipeline)"""

DATA_DIR = dataset_dir
OUT_DIR = Path("/content/task1_outputs")

MASK_DIR = OUT_DIR / "sam_masks"
UNION_DIR = OUT_DIR / "union_masks"
OVERLAY_DIR = OUT_DIR / "sam_overlays"
REPORT_PATH = OUT_DIR / "sam_report.csv"

for folder in (MASK_DIR, UNION_DIR, OVERLAY_DIR):
    folder.mkdir(parents=True, exist_ok=True)

fields = [
    "image", "split", "n_raw", "n_eggs",
    "scores", "areas", "flags", "seconds",
]

def get_split(path):
    for part in path.parts:
        if part in {"train", "test", "valid"}:
            return part
    return "unknown"

# Crash-safe resume: load existing report rows into a dict to prevent duplicate CSV entries
completed_records = {}
if REPORT_PATH.exists() and REPORT_PATH.stat().st_size > 0:
    with REPORT_PATH.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            completed_records[row["image"]] = row

pending_paths = []
for path in image_paths:
    rel = path.relative_to(DATA_DIR)
    key = rel.as_posix()
    m_p = (MASK_DIR / rel).with_suffix(".png")
    u_p = (UNION_DIR / rel).with_suffix(".png")
    o_p = (OVERLAY_DIR / rel).with_suffix(".jpg")

    # Only treat as completed if recorded in CSV AND all 3 output files exist on disk
    if key in completed_records and m_p.exists() and u_p.exists() and o_p.exists():
        continue
    # Incomplete or re-run: remove any stale CSV record to prevent duplicates
    completed_records.pop(key, None)
    pending_paths.append(path)

print(f"Skipping {len(image_paths) - len(pending_paths)} completed images. Processing {len(pending_paths)}...")

dataset = EggImageDataset(pending_paths)
loader = DataLoader(
    dataset,
    batch_size=1,
    num_workers=2,
    collate_fn=lambda b: b[0],
    pin_memory=(device == "cuda"),
)

io_pool = ThreadPoolExecutor(max_workers=2)
futures = []

with REPORT_PATH.open("w" if not completed_records else "a", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(f, fieldnames=fields)
    if not completed_records:
        writer.writeheader()

    for path, img_np in tqdm(loader, total=len(pending_paths), desc="Segmenting"):
        start = time.time()
        pil_img = Image.fromarray(img_np)

        with torch.inference_mode(), torch.autocast(device_type=device, dtype=amp_dtype):
            state = processor.set_image(pil_img)
            result = processor.set_text_prompt(state=state, prompt="egg")

        masks = result["masks"].detach().float().cpu().numpy()
        if masks.ndim == 4:
            masks = masks[:, 0]
        masks = masks.astype(bool)
        scores = result["scores"].detach().float().cpu().numpy().reshape(-1)

        kept = select_masks_vectorized(masks, scores)

        height, width = img_np.shape[:2]
        labels = np.zeros((height, width), dtype=np.uint16)

        # Occlusion handling: paint largest masks first, smallest masks last
        # so smaller occluded eggs preserve their instance boundaries
        kept_by_area_desc = sorted(kept, key=lambda idx: masks[idx].sum(), reverse=True)
        for label_id, i in enumerate(kept_by_area_desc, start=1):
            labels[masks[i]] = label_id

        union = (labels > 0).astype(np.uint8) * 255
        overlay_img = make_overlay(pil_img, masks, scores, kept)

        rel = path.relative_to(DATA_DIR)
        key = rel.as_posix()
        mask_path = (MASK_DIR / rel).with_suffix(".png")
        union_path = (UNION_DIR / rel).with_suffix(".png")
        overlay_path = (OVERLAY_DIR / rel).with_suffix(".jpg")

        # Offload file writes to background thread pool
        futures.append(
            io_pool.submit(
                save_outputs_worker, labels, union, overlay_img, mask_path, union_path, overlay_path
            )
        )

        areas = [float(masks[i].mean()) for i in kept]
        selected_scores = [float(scores[i]) for i in kept]

        flags = []
        if not kept:
            flags.append("NO_DETECTION")
        if len(kept) > 1:
            flags.append("MULTI_EGG")
        if any(s < 0.5 for s in selected_scores):
            flags.append("LOW_SCORE")
        if any(a > 0.90 for a in areas):
            flags.append("VERY_LARGE_MASK")

        row = {
            "image": key,
            "split": get_split(path),
            "n_raw": len(masks),
            "n_eggs": len(kept),
            "scores": ";".join(f"{s:.3f}" for s in selected_scores),
            "areas": ";".join(f"{a:.4f}" for a in areas),
            "flags": "|".join(flags),
            "seconds": f"{time.time() - start:.2f}",
        }
        completed_records[key] = row
        writer.writerow(row)
        f.flush()

# Ensure all background disk writes finish before downstream steps
print("Finalizing background file writes...")
for fut in futures:
    fut.result()
io_pool.shutdown()

print("\nTask 1 inference finished.")
print("Saved outputs:", OUT_DIR)

